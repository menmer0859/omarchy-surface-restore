'use strict';
const assert = require('node:assert/strict');
let p;
try { p = require('../assets/omarchy-lock/LockActivityPolicy.js'); } catch (e) { if(e.code !== 'MODULE_NOT_FOUND') throw e; }
assert.ok(p, 'display/idle requests need a tested sequencing policy');
let s=p.createState();
let r=p.transition(s,{type:'WAKE',force:true,now:0});
assert.deepEqual(r.effects,['WAKE']); s=r.state;
r=p.transition(s,{type:'BLANK',now:10});
assert.deepEqual(r.effects,[], 'blank waits for in-flight wake before running off command'); s=r.state;
r=p.transition(s,{type:'WAKE_FINISHED'});
assert.deepEqual(r.effects,['BLANK']); s=r.state;
r=p.transition(s,{type:'WAKE',deliberate:false,now:30});
assert.deepEqual(r.effects,[], 'blanking rejects residual pointer movement');
r=p.transition(r.state,{type:'BLANK_FINISHED',now:40});
assert.deepEqual(r.effects,[]); s=r.state;
r=p.transition(s,{type:'WAKE',deliberate:false,now:100});
assert.deepEqual(r.effects,[], 'release/motion noise after blank cannot undo screen off');
r=p.transition(r.state,{type:'WAKE',deliberate:true,now:100});
assert.deepEqual(r.effects,['WAKE'], 'new deliberate user press can wake immediately');
s=p.transition(p.createState(),{type:'BLANK',now:0}).state;
s=p.transition(s,{type:'WAKE',deliberate:true,now:20}).state;
r=p.transition(s,{type:'BLANK_FINISHED',now:50});
assert.deepEqual(r.effects,['WAKE'], 'new intentional wake waits until blank completes');
s=p.createState();
assert.deepEqual(p.transition(s,{type:'WAKE',deliberate:false,now:2000}).effects,[], 'lit pointer activity never runs a redundant external wake command');
assert.equal(p.idleDelay({passwordMode:false,passwordLength:0,busy:false,blanked:false}),30000);
assert.equal(p.idleDelay({passwordMode:true,passwordLength:0,busy:false,blanked:false}),60000);
assert.equal(p.idleDelay({passwordMode:true,passwordLength:4,busy:false,blanked:false}),0,'partial password protects thinking time');
assert.equal(p.idleDelay({passwordMode:true,passwordLength:6,busy:false,blanked:false}),0,'completed unsubmitted password is protected');
assert.equal(p.idleDelay({passwordMode:true,passwordLength:0,busy:true,blanked:false}),0);
assert.equal(p.idleDelay({passwordMode:false,passwordLength:0,busy:false,blanked:true}),0);
console.log('Lock activity sequencing and editing regressions passed.');
